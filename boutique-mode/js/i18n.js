const SUPPORTED_LANGS = Object.keys(TRANSLATIONS);
let currentLang = localStorage.getItem("madame_store_lang");
if (!SUPPORTED_LANGS.includes(currentLang)) {
  currentLang = navigator.language && navigator.language.toLowerCase().startsWith("en") ? "en" : "fr";
}

function getLang() {
  return currentLang;
}

function t(key) {
  return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) || TRANSLATIONS.fr[key] || key;
}

function applyStaticTranslations() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(el => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
  document.querySelectorAll("#langSwitch [data-lang]").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === currentLang);
  });
}

function setLanguage(lang) {
  if (!SUPPORTED_LANGS.includes(lang) || lang === currentLang) return;
  currentLang = lang;
  localStorage.setItem("madame_store_lang", lang);
  applyStaticTranslations();
  if (typeof onLanguageChange === "function") onLanguageChange();
}

document.addEventListener("DOMContentLoaded", () => {
  applyStaticTranslations();

  document.querySelectorAll("#langSwitch [data-lang]").forEach(btn => {
    btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
  });
});
